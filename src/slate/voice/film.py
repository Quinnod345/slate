"""A film as the voice stages see it: its lines, direction, timing, voice profile, takes and pins.

Everything the voice stages know lives in the film folder:

    script/storyboard.json        the lines (generated by `slate script build`; each shot's `vo`)
    voice/direction.json          the tagged script: {"lines": {shot: "[tag] words"}} (`slate voice tags set`)
    voice/takes/<shot>/<take>.wav the raw read, with <take>.json (model, voice, settings, seed, request id)
    voice/takes/<shot>/<take>.clean.wav, <take>.paced.wav   the clean-up and pacing stages
    voice/takes/<shot>/<take>.polished.wav, <take>.polish.json   the studio polish and its report (the raw, clean and
                                  paced files stay as they are; voice measurements keep reading those)
    voice/takes.json              which take each shot uses, its stage files and its approval
    voice/align/<shot>.json       word timings of the shot's final take (Whisper-shaped JSON, engine recorded)
    timing/shots.json, timing/vo_cues.json   read for fit (from `slate timing`), when they exist

Pins and locks go through `slate.state` (docs/ARCHITECTURE.md §12). Until that module is installed, a minimal
stand-in keeps pins in film.json "pins" (the documented key `slate.config.model` reads) and locks in
voice/locks.json, and says so once.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import importlib
from functools import cached_property
from pathlib import Path
from typing import Any

from slate import clock as clock_mod
from slate import jsonio, log
from slate.errors import MissingPrerequisite, Refused, SpendRefused, UsageError


def _judged_mode(film_dir: Path, data: dict) -> str:
    """The mode the film is judged in: Slate's own record (slate.state.autonomy.film_mode) holds a film made
    autonomous autonomous, whatever its film.json says now. film.json's own mode without the state module."""
    own = str((data or {}).get("mode") or "supervised")
    try:
        from slate.state import autonomy  # noqa: PLC0415 - the voice stage works without film state installed
    except ImportError:
        return own
    try:
        return autonomy.film_mode(film_dir, data)
    except Exception:  # noqa: BLE001 - an unreadable record never makes a film less strict than its film.json
        return own
from slate.voice import profile as profile_mod
from slate.voice import tags as tags_mod

GENERATED = "do not edit by hand: slate voice"
# A take's stage files, in the order they're made (approval locks every one that exists).
TAKE_STAGES = ("raw", "clean", "paced", "polished")
_warned: set[str] = set()


def now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")


