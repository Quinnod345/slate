# slate.state, or a small stand-in until it's installed


def _state(name: str):
    try:
        return importlib.import_module(f"slate.state.{name}")
    except ModuleNotFoundError as exc:
        if str(exc.name or "").startswith("slate.state"):
            if name not in _warned:
                _warned.add(name)
                log.warn(f"slate.state.{name} isn't installed; the voice stages are using their own minimal stand-in")
            return None
        raise


def load_film(film_dir: Path) -> dict:
    mod = _state("film")
    if mod is not None and hasattr(mod, "load"):
        return mod.load(film_dir)
    path = Path(film_dir) / "film.json"
    if not path.is_file():
        raise UsageError(f"No film.json in {film_dir}.", hint="slate new <id> --brand <brand> --format <format>")
    return jsonio.read(path)


def get_pin(film_dir: Path, key: str) -> Any:
    mod = _state("pins")
    if mod is not None:
        return mod.get(film_dir, key)
    return (jsonio.read(Path(film_dir) / "film.json").get("pins") or {}).get(key)


def pin(film_dir: Path, key: str, value: Any, *, repin: bool = False, approved_by: str | None = None,
        reason: str | None = None, source: str | None = None) -> Any:
    """Pin at first use (first use wins); returns what is pinned now. A re-pin needs who approved it and why."""
    mod = _state("pins")
    if mod is not None:
        return mod.pin(film_dir, key, value, repin=repin, approved_by=approved_by, reason=reason, source=source)
    if repin and not ((approved_by or "").strip() and (reason or "").strip()):
        raise Refused(f"Re-pinning {key} is explicit: say who approved it and why.")
    path = Path(film_dir) / "film.json"
    data = jsonio.read(path)
    pins = data.setdefault("pins", {})
    if key in pins and not repin:
        return pins[key]
    data.setdefault("pin_log", []).append({"key": key, "event": "repin" if key in pins else "pin", "at": now(),
                                           "value": value, "previous": pins.get(key), "approved_by": approved_by,
                                           "reason": reason, "source": source})
    pins[key] = value
    jsonio.write_atomic(path, data)
    return value


def source(film_dir: Path, rel_path: str) -> Path:
    """A file to read: the film's own, else, in a derived film, the parent's file it reuses by reference
    (slate.state.lock.resolve). Only for reading: a derived film writes its own files."""
    own = Path(film_dir) / rel_path
    if own.exists():
        return own
    mod = _state("lock")
    if mod is None or not hasattr(mod, "resolve"):
        return own
    try:
        return Path(mod.resolve(film_dir, rel_path))
    except Exception:  # noqa: BLE001 - a broken reference reads as missing, which every caller handles
        return own


def record(film_dir: Path, rel_path: str, *, producer: str, inputs: Any, tool_version: str | None = None,
           note: str | None = None) -> dict:
    mod = _state("lock")
    if mod is not None:
        if note is not None:
            try:
                return mod.record(film_dir, rel_path, producer=producer, inputs=inputs, tool_version=tool_version,
                                  note=note)
            except TypeError:  # a state module without notes: the record still counts, without the note
                pass
        return mod.record(film_dir, rel_path, producer=producer, inputs=inputs, tool_version=tool_version)
    return {"producer": producer, "inputs": inputs, "tool_version": tool_version, "made_at": now(), "locked": False,
            "note": note}


def _locks_path(film_dir: Path) -> Path:
    return Path(film_dir) / "voice" / "locks.json"


def lock_asset(film_dir: Path, rel_path: str, *, reason: str, by: str | None = None) -> None:
    mod = _state("lock")
    if mod is not None:
        mod.lock_asset(film_dir, rel_path, reason=reason, by=by)
        return
    path = _locks_path(film_dir)
    locks = jsonio.read(path, default={}) or {}
    full = Path(film_dir) / rel_path
    locks.setdefault("locked", {})[rel_path] = {"sha256": jsonio.sha256(full) if full.is_file() else None,
                                                "reason": reason, "locked_at": now()}
    jsonio.write_atomic(path, {"generated": GENERATED, **{k: v for k, v in locks.items() if k != "generated"}})


def is_locked(film_dir: Path, rel_path: str) -> bool:
    mod = _state("lock")
    if mod is not None and mod.is_locked(film_dir, rel_path):
        return True
    locks = jsonio.read(_locks_path(film_dir), default={}) or {}
    return rel_path in (locks.get("locked") or {})


def guard_regenerate(film_dir: Path, rel_path: str, *, force: bool = False, approval_id: str | None = None,
                     by: str | None = None) -> dict:
    """Before replacing approved work: a locked file needs --force and a person's spend approval covering it."""
    mod = _state("lock")
    if mod is not None and hasattr(mod, "guard_regenerate"):
        return mod.guard_regenerate(film_dir, rel_path, force=force, approval_id=approval_id, by=by)
    if not is_locked(film_dir, rel_path):
        return {"path": rel_path, "allowed": True, "locked": False}
    if not force:
        raise Refused(f"{rel_path} is an approved, locked take. Slate never re-voices approved work on its own.",
                      hint="If a person wants it redone, run again with --force and their spend approval "
                           "(--approval <id>).")
    if not approval_id:
        raise SpendRefused(f"Re-voicing {rel_path} spends again and replaces approved work, so it needs a person's "
                           "spend approval id as well as --force.")
    return {"path": rel_path, "allowed": True, "locked": True, "approval_id": approval_id}


def approve(film_dir: Path, *, what: str, path: str, approved_by: str, note: str | None = None) -> dict:
    mod = _state("approvals")
    if mod is not None:
        return mod.record(film_dir, what=what, path=path, approved_by=approved_by, note=note)
    full = Path(film_dir) / path
    return {"what": what, "path": path, "approved_by": approved_by, "note": note, "at": now(),
            "sha256": jsonio.sha256(full) if full.is_file() else None}


