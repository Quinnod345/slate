# The film


class Line:
    """One voiced line: the shot it belongs to and its plain script words."""

    __slots__ = ("shot", "act", "text", "tagged", "dur", "index")

    def __init__(self, shot: str, act: Any, text: str, tagged: str | None, dur: float | None, index: int):
        self.shot, self.act, self.text, self.tagged, self.dur, self.index = shot, act, text, tagged, dur, index

    def to_dict(self) -> dict:
        return {"shot": self.shot, "act": self.act, "text": self.text, "tagged": self.tagged, "dur": self.dur}


class VoiceFilm:
    def __init__(self, film_dir: str | Path):
        self.dir = Path(film_dir).resolve()
        if not (self.dir / "film.json").is_file():
            raise UsageError(f"{self.dir} isn't a film folder (no film.json).")
        self.data = load_film(self.dir)
        self.id = str(self.data.get("id") or self.dir.name)
        self.mode = _judged_mode(self.dir, self.data)
        self.language = str(self.data.get("language") or "en")

    # -- paths --------------------------------------------------------------------------------------------------

    def rel(self, path: str | Path) -> str:
        p = Path(path)
        try:
            return str(p.resolve().relative_to(self.dir))
        except ValueError:
            return str(p)

    def path(self, rel: str) -> Path:
        return self.dir / rel

    # -- voice profile ------------------------------------------------------------------------------------------

    @cached_property
    def profile(self) -> dict:
        return profile_mod.for_film(self.dir, self.data)

    # -- lines --------------------------------------------------------------------------------------------------

    @cached_property
    def storyboard(self) -> dict:
        path = self.dir / "script" / "storyboard.json"
        if not path.is_file():
            raise MissingPrerequisite("This film has no storyboard yet, so there are no lines to voice.",
                                      hint="Run `slate script build` first.")
        return jsonio.read(path)

    @cached_property
    def lines(self) -> list[Line]:
        out: list[Line] = []
        for act in self.storyboard.get("acts") or []:
            act_id = act.get("id", act.get("act", act.get("name")))
            for shot in act.get("shots") or []:
                text = " ".join(str(shot.get("vo") or shot.get("line") or "").split())
                if not text:
                    continue
                tagged = shot.get("vo_tagged") or shot.get("tagged")
                dur = shot.get("dur", shot.get("duration"))
                out.append(Line(str(shot["id"]), act_id, tags_mod.strip(text) if tags_mod.tags_in(text) else text,
                                tagged, float(dur) if dur is not None else None, len(out)))
        return out

    def line(self, shot: str) -> Line:
        for ln in self.lines:
            if ln.shot == shot:
                return ln
        raise UsageError(f"Shot {shot} has no voice line in this film's storyboard.")

    def select(self, only: str | list[str] | None) -> list[Line]:
        if not only:
            return list(self.lines)
        wanted = [s.strip() for s in (only.split(",") if isinstance(only, str) else only) if s.strip()]
        known = {ln.shot for ln in self.lines}
        missing = [s for s in wanted if s not in known]
        if missing:
            raise UsageError(f"No voice line for {', '.join(missing)} (lines: {', '.join(sorted(known)) or 'none'}).")
        return [ln for ln in self.lines if ln.shot in wanted]

    def neighbours(self, shot: str) -> tuple[str | None, str | None]:
        """The previous and next lines' plain words (context never carries tags: a tag belongs to its own line). A line
        whose direction drops a side (`context_for`) is read without it."""
        ln = self.line(shot)
        ctx = self.context_for(shot)
        prev = self.lines[ln.index - 1].text if ln.index > 0 and ctx.get("previous", True) else None
        nxt = self.lines[ln.index + 1].text if ln.index + 1 < len(self.lines) and ctx.get("next", True) else None
        return prev, nxt

    def context_for(self, shot: str) -> dict:
        """A line's reading context, from voice/direction.json's "context": {"S03": {"next": false, "why": "…"}}.
        A neighbour set to false isn't sent: neither its words nor its takes' request ids. For a line the next one
        carries on from in the script, but which has to be read to its own end (a question that stops): with the next
        line in context the model reads straight on into it."""
        data = jsonio.read(self.direction_path, default={}) or {}
        ctx = (data.get("context") or {}).get(shot) or {}
        return {k: bool(ctx[k]) for k in ("previous", "next") if k in ctx}

    # -- direction ----------------------------------------------------------------------------------------------

    @property
    def direction_path(self) -> Path:
        return self.dir / "voice" / "direction.json"

    def direction(self) -> dict[str, str]:
        data = jsonio.read(self.direction_path, default={}) or {}
        return dict(data.get("lines") or {})

    def tagged_for(self, shot: str) -> str:
        """What is sent for a line: its direction, else the storyboard's tagged form, else the plain words."""
        ln = self.line(shot)
        return self.direction().get(shot) or ln.tagged or ln.text

    def set_direction(self, shot: str, tagged: str | None) -> Path:
        data = jsonio.read(self.direction_path, default={}) or {}
        lines = dict(data.get("lines") or {})
        if tagged is None or tagged == self.line(shot).text:
            lines.pop(shot, None)
        else:
            lines[shot] = tagged
        order = {ln.shot: ln.index for ln in self.lines}
        ordered = dict(sorted(lines.items(), key=lambda kv: order.get(kv[0], 1 << 30)))
        return jsonio.write_atomic(self.direction_path, {
            "note": "The tagged script: each line's audio tags. Tags direct delivery and never change the words; "
                    "every line must strip back to the storyboard exactly (slate voice tags check).",
            "lines": ordered})

    # -- timing -------------------------------------------------------------------------------------------------

    @cached_property
    def shots_json(self) -> dict | None:
        path = self.dir / "timing" / "shots.json"
        return jsonio.read(path) if path.is_file() else None

    @cached_property
    def clock(self) -> clock_mod.Clock:
        return clock_mod.from_film(self.shots_json or self.data)

    def shot_seconds(self, shot: str) -> float | None:
        """How long a shot runs: frame-exact from timing/shots.json, else the storyboard's duration."""
        sj = self.shots_json
        if sj:
            ck = clock_mod.from_film(sj)
            for s in sj.get("shots") or []:
                if s.get("id") == shot and s.get("frame_in") is not None and s.get("frame_out") is not None:
                    return ck.secs_of(int(s["frame_out"])) - ck.secs_of(int(s["frame_in"]))
        try:
            return self.line(shot).dur
        except UsageError:
            return None

    @cached_property
    def vo_cues(self) -> dict[str, dict]:
        path = self.dir / "timing" / "vo_cues.json"
        data = jsonio.read(path) if path.is_file() else {}
        return {c["shot"]: c for c in (data.get("cues") or []) if c.get("shot")}

    def lead(self, shot: str) -> float:
        """Where the read starts inside its shot: the cue sheet's `at`, else the profile's lead."""
        cue = self.vo_cues.get(shot)
        if cue and cue.get("at") is not None:
            return float(cue["at"])
        return float(self.profile["fit"]["lead_s"])

    # -- takes --------------------------------------------------------------------------------------------------

    @property
    def manifest_path(self) -> Path:
        return self.dir / "voice" / "takes.json"

    def manifest(self) -> dict:
        data = jsonio.read(self.manifest_path, default=None) or {}
        data.setdefault("shots", {})
        return data

    def save_manifest(self, data: dict) -> Path:
        order = {ln.shot: ln.index for ln in self.lines} if (self.dir / "script" / "storyboard.json").is_file() else {}
        shots = dict(sorted(data.get("shots", {}).items(), key=lambda kv: (order.get(kv[0], 1 << 30), kv[0])))
        return jsonio.write_atomic(self.manifest_path, {
            "generated": GENERATED,
            "note": "Which take each shot uses, its stage files (raw, clean, paced, polished), alignment and approval.",
            "shots": shots})

    def take_dir(self, shot: str) -> Path:
        return self.dir / "voice" / "takes" / shot

    def take_ids(self, shot: str) -> list[str]:
        folder = self.take_dir(shot)
        if not folder.is_dir():
            return []
        return sorted(p.stem for p in folder.glob("t[0-9][0-9]*.json"))

    def next_take_id(self, shot: str) -> str:
        nums = [int(t[1:]) for t in self.take_ids(shot) if t[1:].isdigit()]
        return f"t{(max(nums) + 1) if nums else 1:02d}"

    def take_json(self, shot: str, take: str) -> dict:
        return jsonio.read(self.take_dir(shot) / f"{take}.json")

    def save_take_json(self, shot: str, take: str, data: dict) -> Path:
        return jsonio.write_atomic(self.take_dir(shot) / f"{take}.json", data)

    def entry(self, shot: str) -> dict | None:
        return self.manifest()["shots"].get(shot)

    def selected(self, shot: str) -> tuple[str, dict] | None:
        e = self.entry(shot)
        if not e or not e.get("selected"):
            return None
        return e["selected"], e["takes"][e["selected"]]

    STAGES = ("polished", "paced", "clean", "raw")  # the last stage a take reached comes first

    def final_audio(self, shot: str, *, polished: bool = True) -> Path | None:
        """The take's audio as the film uses it: its last stage (polished, paced, clean, then raw). With
        polished=False, the last stage before the polish: what voice measurements read."""
        stage = self.final_stage(shot, polished=polished)
        return self.dir / self.selected(shot)[1][stage] if stage else None

    def final_stage(self, shot: str, *, polished: bool = True) -> str | None:
        sel = self.selected(shot)
        if not sel:
            return None
        for stage in self.STAGES if polished else self.STAGES[1:]:
            if sel[1].get(stage) and (self.dir / sel[1][stage]).is_file():
                return stage
        return None

    def unpolished_audio(self, shot: str) -> Path | None:
        """The take before the studio polish (paced, clean or raw): what the polish reads, and what breath, pitch and
        tag measurements read, so a polished take is never its own baseline."""
        return self.final_audio(shot, polished=False)

    def timing_stage(self, shot: str) -> str | None:
        """The stage whose timing the final audio has. The polish keeps every sample where it was, so a polished take
        times like the stage it was polished from."""
        stage = self.final_stage(shot)
        if stage != "polished":
            return stage
        take = self.selected(shot)[0]
        source = ((self.take_json(shot, take).get("stages") or {}).get("polish") or {}).get("source_stage")
        return source or self.final_stage(shot, polished=False)

    def update_take(self, shot: str, take: str, **fields: Any) -> dict:
        data = self.manifest()
        entry = data["shots"].setdefault(shot, {"selected": None, "takes": {}, "approved": None})
        info = entry["takes"].setdefault(take, {})
        info.update(fields)
        self.save_manifest(data)
        return info

    def select_take(self, shot: str, take: str) -> None:
        data = self.manifest()
        entry = data["shots"].setdefault(shot, {"selected": None, "takes": {}, "approved": None})
        if take not in entry["takes"]:
            raise UsageError(f"{shot} has no take {take} (takes: {', '.join(entry['takes']) or 'none'}).")
        entry["selected"] = take
        self.save_manifest(data)

    def approved(self, shot: str) -> dict | None:
        e = self.entry(shot)
        return (e or {}).get("approved")

    def locked(self, shot: str) -> bool:
        """True when the shot's selected take is approved and locked (its stage files are locked by hash)."""
        sel = self.selected(shot)
        if not sel:
            return False
        take, info = sel
        return bool(self.approved(shot)) or any(is_locked(self.dir, info[s]) for s in TAKE_STAGES if info.get(s))

    # -- seeds --------------------------------------------------------------------------------------------------

    def seed_for(self, shot: str) -> int:
        """The profile's seed when it has one, else a stable seed per line (same line, same seed)."""
        seed = self.profile.get("seed")
        if seed is not None:
            return int(seed)
        return int(hashlib.sha256(f"{self.id}|{shot}".encode()).hexdigest()[:8], 16) % 2_147_483_647
