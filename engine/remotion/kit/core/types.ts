// The shapes the kit reads. Python resolves every frame and writes these files into the film folder; the engine's
// generated entry bundles them as one module, `@film/data`, and the kit only ever reads that module. Nothing here
// derives a frame boundary of its own, which is what keeps Remotion, the web engine and After Effects on one clock.
//
// The shapes follow docs/ARCHITECTURE.md §5 (the films' proven timing files). Keys the kit doesn't use are kept, so a
// scene can read them straight from `filmData()`.

/** One word of a read, in seconds from the start of its take (timing/vo_words.json). */
export type Word = {w: string; start: number; end: number; [key: string]: unknown};

/** One shot of timing/shots.json. Frames are film frames (frame 0 is the film's first frame). */
export type ShotRecord = {
  id: string;
  act: number | string;
  frame_in: number;
  frame_out: number;
  frames?: number;
  sec_in?: number;
  sec_out?: number;
  vo?: string;
  on_screen?: string;
  picture?: string;
  [key: string]: unknown;
};

export type ShotsFile = {
  fps_num?: number;
  fps_den?: number;
  width?: number;
  height?: number;
  total_frames?: number;
  acts?: unknown[];
  shots: ShotRecord[];
  [key: string]: unknown;
};

/** timing/vo_cues.json: where each shot's read is placed, `at` seconds into the shot. */
export type VoCue = {shot: string; at: number; file?: string; gain?: number; fade_in?: number; fade_out?: number; [key: string]: unknown};
export type VoCuesFile = {cues: VoCue[]; [key: string]: unknown};

/** timing/vo_words.json: every shot's read, word by word. */
export type VoWordsFile = {shots: Record<string, {take?: string; line?: string; words: Word[]; [key: string]: unknown}>; [key: string]: unknown};

/** film.json, the parts the picture needs. fps and size come from here and nowhere else. */
export type FilmInfo = {
  id: string;
  title?: string;
  fps_num: number;
  fps_den: number;
  width: number;
  height: number;
  language?: string;
  format?: string;
  brand?: string;
  [key: string]: unknown;
};

/**
 * The one module a film's scenes read (`import data from '@film/data'`), generated by the engine from the film folder:
 * film.json, timing/*.json, the brand pack, and the spoken forms Python resolved for every number or symbol in the
 * script's lines (timing.spoken.forms), so the kit never needs a language table of its own.
 */
export type FilmData = {
  film: FilmInfo;
  shots: ShotsFile;
  vo_cues?: VoCuesFile;
  vo_words?: VoWordsFile;
  timeline?: unknown;
  captions?: unknown;
  /** token -> the ways it is said, each a list of words: {"64": [["sixty-four"]], "&": [["and"]]} */
  spoken?: Record<string, string[][]>;
  /** the brand pack (brand.json) with its logo SVGs inlined as text */
  brand?: BrandPack;
  /** the act this entry was generated for, when it was generated for one */
  act?: number | string;
  [key: string]: unknown;
};

// ---------------------------------------------------------------------------------------------------------- brand pack
// A brand pack is data (docs/ARCHITECTURE.md §7). The kit reads it loosely, because packs are written by people and by
// onboarding: every reader below accepts a few spellings, fills what it can derive, and lists what it had to assume in
// `problems` rather than throwing (a throw at module load would take down every composition in the bundle).

export type ColorValue = string;
export type PaletteTree = {[key: string]: ColorValue | PaletteTree};

export type FontSourceInput =
  | string
  | {kind?: string; type?: string; name?: string; family?: string; url?: string; href?: string; format?: string; [key: string]: unknown};

export type FamilyInput = {
  role?: string;
  id?: string;
  name?: string;
  family?: string;
  weights?: (number | string)[];
  styles?: string[];
  source?: FontSourceInput;
  licence?: string;
  license?: string;
  fallback?: string;
  [key: string]: unknown;
};

export type TypeScaleInput = Record<
  string,
  {family?: string; role?: string; weight?: number | string; size?: number; line?: number; lineHeight?: number; tracking?: number; letterSpacing?: number; transform?: string; case?: string; numeric?: string; [key: string]: unknown}
>;

export type BrandType = {
  families?: FamilyInput[] | Record<string, FamilyInput>;
  scale?: TypeScaleInput;
  /** the short side (px) the scale's sizes were written for, when they are px rather than fractions */
  reference?: number;
  [key: string]: unknown;
};

export type EaseInput =
  | string
  | number[]
  | {bezier?: number[]; cubic_bezier?: number[] | string; kind?: string; type?: string; stiffness?: number; lineage?: string; [key: string]: unknown};

export type BrandMotion = {
  eases?: Record<string, EaseInput>;
  durations?: Record<string, number | {seconds?: number; s?: number; [key: string]: unknown}> | {name: string; seconds: number}[];
  staggers?: Record<string, number | {seconds?: number; frames?: number; at_fps?: number; [key: string]: unknown}>;
  stagger_cap?: {seconds?: number; fraction?: number};
  exit_factor?: number;
  roles?: Record<string, string>;
  overshoot?: {allowed?: boolean; max?: number; where?: string[]; [key: string]: unknown};
  signature?: unknown;
  [key: string]: unknown;
};

export type LogoInput = {
  svg?: string;
  path?: string;
  file?: string;
  build?: Record<string, unknown>;
  [key: string]: unknown;
};

export type BrandPack = {
  name?: string;
  palette?: PaletteTree & {roles?: Record<string, string>; tones?: Record<string, Record<string, string>>};
  type?: BrandType;
  logos?: Record<string, LogoInput> | LogoInput[];
  motif?: Record<string, unknown> | null;
  look?: {id?: string; overrides?: Record<string, unknown>; references?: unknown; [key: string]: unknown} | string | null;
  motion?: BrandMotion;
  [key: string]: unknown;
};
