const SCENE_EXTS = ['.tsx', '.ts', '.jsx', '.js'];

/** The act's module, scenes/act<N>/index.*, or null when the act isn't built yet. */
export function sceneIndex(filmDir, act) {
  const dir = path.join(filmDir, 'scenes', `act${act}`);
  for (const ext of SCENE_EXTS) {
    const f = path.join(dir, `index${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

function actModule(filmDir, act, name) {
  const dir = path.join(filmDir, 'scenes', `act${act}`);
  for (const ext of [...SCENE_EXTS, '.mjs']) {
    const f = path.join(dir, `${name}${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

/** An act's optional events module, scenes/act<N>/events.*. */
export const sceneEvents = (filmDir, act) => actModule(filmDir, act, 'events');

/** An act's optional beats module, scenes/act<N>/beats.*: React-free, computed at module level (the films' pattern). */
export const sceneBeats = (filmDir, act) => actModule(filmDir, act, 'beats');

export function contractsModule(filmDir) {
  for (const ext of SCENE_EXTS) {
    const f = path.join(filmDir, 'scenes', `contracts${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

/** The kit's entry file, or null while the kit isn't installed in this engine. */
export function kitEntry() {
  for (const ext of ['.ts', '.tsx', '.js', '.mjs']) {
    const f = path.join(KIT_DIR, `index${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

/** Whether this engine has a kit folder at all ('@slate/kit' and '@slate/kit/core' resolve into it). */
export const kitPresent = () => fs.existsSync(KIT_DIR);

/**
 * Where the engine reads the kit's registries from: '@slate/kit/core' (React-free; the kit keeps its clock, motion
 * and event registries there) when it exists, else '@slate/kit'. Both resolve to the same module instances in a bundle.
 */
export function kitHooksModule() {
  for (const ext of ['.ts', '.tsx', '.js', '.mjs']) {
    if (fs.existsSync(path.join(KIT_DIR, 'core', `index${ext}`))) return '@slate/kit/core';
  }
  return kitEntry() ? '@slate/kit' : null;
}

