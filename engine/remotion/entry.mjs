/**
 * entry.tsx: registerRoot(Root), after registering a loader for each of the brand's Google Fonts families (the kit's
 * FontGate refuses a Google face nobody registered). `google` is [{family, module}] from the kit's own font plan.
 */
function entrySource(google) {
  const usable = google.filter((g) => g.module);
  const lines = [`// ${GENERATED_NOTE}`, "import {registerRoot} from 'remotion';"];
  if (usable.length) lines.push("import {registerGoogleFont} from '@slate/kit';");
  usable.forEach((g, i) => lines.push(`import {loadFont as loadFont${i}} from '${g.module}';`));
  lines.push("import {Root} from './Root';", '');
  if (usable.length) {
    lines.push("// The brand's Google Fonts families, registered before anything renders (the kit's FontGate loads them).");
    usable.forEach((g, i) => lines.push(`registerGoogleFont(${JSON.stringify(g.family)}, loadFont${i});`));
  }
  lines.push('registerRoot(Root);', '');
  return lines.join('\n');
}

