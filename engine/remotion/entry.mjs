// Entry generation: turns a film folder into something Remotion can bundle, with no relative imports reaching
// into the engine (the films' scenes imported their kit and data 4–5 levels up; one moved folder broke them all).
//
// From timing/shots.json and scenes/act<N>/, this writes <film>/.slate/:
//   entry.tsx       registerRoot(Root)
//   Root.tsx        one composition per act (Act1…ActN), the whole film (Film), and a Contract-<Name> still for each
//                   rest state exported by scenes/contracts.tsx
//   film-data.ts    what scenes import as '@film/data': the film's size and rate, its acts, and its timing JSON
//   placeholder.tsx an act that isn't built yet renders its shot ids, on-screen text and VO, so every act (and the
//                   whole film) renders from day one
//   label.tsx       the frame label contact sheets burn into their cells
// and <film>/tsconfig.json, so a type check runs from the film folder against the engine's kit and packages.
//
// Scenes import '@slate/kit' (engine/remotion/kit) and '@film/data'. Every act exports its component as default;
// it receives {sub, act, firstFrame}: the motion-blur sample count, its act number and its first film frame.
import fs from 'node:fs';
import path from 'node:path';
import {build} from 'esbuild';
import {ENGINE_DIR, KIT_DIR, NODE_MODULES, readJson, usage, writeIfChanged} from './lib/common.mjs';
import {googleFamilies} from './kit_bridge.mjs';
import {DATA_KEYS, FILM_COMP, SPOKEN_FALLBACK, TIMING_FILES, compIdForAct} from './lib/film.mjs';

export const GENERATED_NOTE =
  "Generated by Slate's engine (node engine/cli.mjs entry). Do not edit by hand: it is rewritten before every " +
  'bundle, render, still, emit-events and check.';

const SCENE_EXTS = ['.tsx', '.ts', '.jsx', '.js'];

/** The act's module, scenes/act<N>/index.*, or null when the act isn't built yet. */
export function sceneIndex(filmDir, act) {
  const dir = path.join(filmDir, 'scenes', `act${act}`);
  for (const ext of SCENE_EXTS) {
    const f = path.join(dir, `index${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

function actModule(filmDir, act, name) {
  const dir = path.join(filmDir, 'scenes', `act${act}`);
  for (const ext of [...SCENE_EXTS, '.mjs']) {
    const f = path.join(dir, `${name}${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

/** An act's optional events module, scenes/act<N>/events.*. */
export const sceneEvents = (filmDir, act) => actModule(filmDir, act, 'events');

/** An act's optional beats module, scenes/act<N>/beats.*: React-free, computed at module level (the films' pattern). */
export const sceneBeats = (filmDir, act) => actModule(filmDir, act, 'beats');

export function contractsModule(filmDir) {
  for (const ext of SCENE_EXTS) {
    const f = path.join(filmDir, 'scenes', `contracts${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

/** The kit's entry file, or null while the kit isn't installed in this engine. */
export function kitEntry() {
  for (const ext of ['.ts', '.tsx', '.js', '.mjs']) {
    const f = path.join(KIT_DIR, `index${ext}`);
    if (fs.existsSync(f)) return f;
  }
  return null;
}

/** Whether this engine has a kit folder at all ('@slate/kit' and '@slate/kit/core' resolve into it). */
export const kitPresent = () => fs.existsSync(KIT_DIR);

/**
 * Where the engine reads the kit's registries from: '@slate/kit/core' (React-free; the kit keeps its clock, motion
 * and event registries there) when it exists, else '@slate/kit'. Both resolve to the same module instances in a bundle.
 */
export function kitHooksModule() {
  for (const ext of ['.ts', '.tsx', '.js', '.mjs']) {
    if (fs.existsSync(path.join(KIT_DIR, 'core', `index${ext}`))) return '@slate/kit/core';
  }
  return kitEntry() ? '@slate/kit' : null;
}

export const slateDir = (filmDir) => path.join(filmDir, '.slate');
export const filmDataFile = (filmDir) => path.join(slateDir(filmDir), 'film-data.ts');

const posix = (p) => p.split(path.sep).join('/');
function importPath(fromDir, file) {
  let rel = posix(path.relative(fromDir, file));
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return rel;
}

/** Export names of a module, read by esbuild without running it. */
export async function moduleExports(file) {
  const res = await build({
    entryPoints: [file],
    bundle: false,
    write: false,
    metafile: true,
    format: 'esm',
    logLevel: 'silent',
    jsx: 'automatic',
    outdir: path.join(path.dirname(file), '.slate-exports'),
  });
  return Object.values(res.metafile.outputs).flatMap((o) => o.exports ?? []);
}

const hasDefaultExport = (text) => /export\s+default\b/.test(text) || /export\s*\{[^}]*\bas\s+default\b/.test(text);

/** The '@film/data' module for a film, written so its imports are relative to `outFile`. */
export function filmDataSource(ctx, outFile, {brand = null, brandDir = null} = {}) {
  const outDir = path.dirname(outFile);
  const f = ctx.film;
  const info = {
    id: ctx.id,
    title: f.title ?? null,
    format: f.format ?? null,
    language: f.language ?? null,
    brand: typeof f.brand === 'string' ? f.brand : (f.brand?.name ?? null),
    fps_num: ctx.fps.num,
    fps_den: ctx.fps.den,
    width: ctx.width,
    height: ctx.height,
  };
  const acts = ctx.acts.map(({act, name, firstShot, lastShot, shots, frameIn, frameOut, frames}) => ({act, name, firstShot, lastShot, shots, frameIn, frameOut, frames}));
  const lines = [
    `// ${GENERATED_NOTE}`,
    "// Scenes and the kit import it as '@film/data'. The default export is the kit's FilmData (film, shots, vo_words,",
    "// vo_cues, timeline, events, captions, spoken, brand): the film's size and frame rate come from film.json, the only",
    '// source of either. A timing file the film has no copy of yet is left out of the default export and null below.',
  ];
  const optional = [];
  for (const [name, rel] of Object.entries(TIMING_FILES)) {
    let file = path.join(ctx.dir, rel);
    if (name === 'spoken' && !fs.existsSync(file)) file = path.join(ctx.dir, SPOKEN_FALLBACK);
    if (fs.existsSync(file)) {
      lines.push(`import ${name}Json from '${importPath(outDir, file)}';`);
      optional.push([name, true]);
    } else {
      optional.push([name, false]);
    }
  }
  if (!optional.find(([n]) => n === 'shots')[1]) throw usage(`${ctx.id} has no timing/shots.json yet.`, 'Run `slate timing` first.');
  lines.push(
    '',
    'export type Shot = {id: string; act: number; frame_in: number; frame_out: number; frames?: number; sec_in?: number; sec_out?: number; vo?: string | null; on_screen?: string | null; [key: string]: unknown};',
    'export type ShotsFile = {fps_num: number; fps_den: number; width: number; height: number; total_frames?: number; acts?: {index?: number; name?: string; shots?: string[]}[]; shots: Shot[]; [key: string]: unknown};',
    'export type FilmInfo = {id: string; title: string | null; format: string | null; language: string | null; brand: string | null; fps_num: number; fps_den: number; width: number; height: number};',
    'export type ActInfo = {act: number; name: string | null; firstShot: string; lastShot: string; shots: string[]; frameIn: number; frameOut: number; frames: number};',
    '/** What every act component receives: the motion-blur sample count, its act number and its first film frame. */',
    'export type SceneProps = {sub: number; act: number; firstFrame: number};',
    'export type JsonObject = {[key: string]: unknown};',
    '',
    `export const film: FilmInfo = ${JSON.stringify(info)};`,
    'export const fps: number = film.fps_num / film.fps_den;',
    `export const acts: ActInfo[] = ${JSON.stringify(acts)};`,
  );
  for (const [name, present] of optional) {
    if (name === 'shots') lines.push('export const shots: ShotsFile = shotsJson as unknown as ShotsFile;');
    else if (name === 'spoken') lines.push(`export const spoken: {[token: string]: string[][]} | null = ${present ? 'spokenJson as unknown as {[token: string]: string[][]}' : 'null'};`);
    else lines.push(`export const ${name}: unknown = ${present ? `${name}Json as unknown` : 'null'};`);
  }
  const defaults = optional.filter(([, present]) => present).map(([name]) => (DATA_KEYS[name] === name ? name : `${DATA_KEYS[name]}: ${name}`));
  if (brand) defaults.push('brand');
  lines.push(
    `export const brand: JsonObject | null = ${brand ? JSON.stringify(brand) : 'null'};`,
    `export const brandDir: string | null = ${brandDir ? JSON.stringify(brandDir) : 'null'};`,
    '',
    '/** The kit\'s FilmData: `import data from \'@film/data\'`. */',
    `const data = {film, ${defaults.join(', ')}, fps, acts, brandDir};`,
    'export default data;',
    '',
  );
  return lines.join('\n');
}

/**
 * A brand pack as the kit reads it: brand.json, with every logo's SVG inlined as text (the kit draws logos from
 * markup; a bundle can't read the brand folder). A logo is {svg?, path?, file?, build?} or a path string.
 */
export function inlineBrand(brandJson, brandDir) {
  const brand = JSON.parse(JSON.stringify(brandJson));
  const inline = (logo) => {
    if (typeof logo === 'string') logo = {path: logo};
    if (!logo || typeof logo !== 'object' || logo.svg) return logo;
    const rel = logo.path ?? logo.file;
    if (typeof rel !== 'string' || !rel.toLowerCase().endsWith('.svg')) return logo;
    const file = path.resolve(brandDir, rel);
    if (!file.startsWith(path.resolve(brandDir) + path.sep) || !fs.existsSync(file)) return logo;
    return {...logo, svg: fs.readFileSync(file, 'utf8')};
  };
  if (Array.isArray(brand.logos)) brand.logos = brand.logos.map(inline);
  else if (brand.logos && typeof brand.logos === 'object') {
    for (const [k, v] of Object.entries(brand.logos)) brand.logos[k] = inline(v);
  }
  if (brand.motif && typeof brand.motif === 'object' && !Array.isArray(brand.motif)) brand.motif = inline(brand.motif);
  return brand;
}

