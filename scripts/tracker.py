#!/usr/bin/env python3
"""Keep the plan tracker honest: fold module reports into docs/plan_points.json and render docs/PLAN_TRACKER.md.

Every point in the plan has an owner. Builders and reviewers write per-point statuses with evidence into
docs/build_reports/<module>.build.json and <module>.review.json; later waves write docs/build_reports/<wave>.json in
the same shape. A reviewer's verdict outranks the builder's, and a later report outranks an earlier one, so the tracker
always shows the most recent, most checked claim. Nothing is marked done without evidence.

usage: scripts/tracker.py [--fold] [--render] [--summary]
"""

from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POINTS = ROOT / "docs" / "plan_points.json"
TRACKER = ROOT / "docs" / "PLAN_TRACKER.md"
REPORTS = ROOT / "docs" / "build_reports"
STATUSES = ("done", "partial", "needs-quinn", "later-wave", "open")
RANK = {"build": 1, "review": 2, "wave": 3, "final": 4}


def _load_points() -> list[dict]:
    return json.loads(POINTS.read_text(encoding="utf-8"))


def _report_kind(path: Path) -> str:
    name = path.name
    if name.endswith(".review.json"):
        return "review"
    if name.endswith(".build.json"):
        return "build"
    if name.startswith("final"):
        return "final"
    return "wave"


def _entries(path: Path) -> list[dict]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"skipping {path.name}: {exc}", file=sys.stderr)
        return []
    points = data.get("points") if isinstance(data, dict) else None
    if not isinstance(points, list):
        return []
    return [p for p in points if isinstance(p, dict) and p.get("id")]


def fold() -> int:
    points = _load_points()
    by_id = {p["id"]: p for p in points}
    best: dict[str, tuple[int, float, dict, str]] = {}
    for path in sorted(REPORTS.glob("*.json")):
        kind = _report_kind(path)
        mtime = path.stat().st_mtime
        for entry in _entries(path):
            pid = str(entry["id"]).strip().upper()
            if pid not in by_id:
                continue
            key = (RANK[kind], mtime)
            if pid not in best or key > best[pid][:2]:
                best[pid] = (RANK[kind], mtime, entry, path.name)
    changed = 0
    for pid, (_, _, entry, source) in best.items():
        status = str(entry.get("status", "open")).lower()
        if status not in STATUSES:
            status = "partial"
        evidence = str(entry.get("evidence", "")).strip()
        if status == "done" and not evidence:
            status = "partial"
            evidence = "(claimed done without evidence)"
        point = by_id[pid]
        new = {"status": status, "evidence": evidence[:600], "source": source}
        if {k: point.get(k) for k in new} != new:
            point.update(new)
            changed += 1
    POINTS.write_text(json.dumps(points, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"folded {len(best)} point reports, {changed} changed")
    return 0


def render() -> int:
    points = _load_points()
    counts = collections.Counter(p.get("status", "open") for p in points)
    lines = [
        "# Slate plan tracker",
        "",
        "Every point in `docs/PLAN.md` (list items, table rows and paragraph-level requirements), who owns it, where it "
        "stands and the evidence. Generated by `scripts/tracker.py --render` from `docs/plan_points.json`; don't edit "
        "by hand.",
        "",
        "**Totals:** " + " · ".join(f"{s} {counts.get(s, 0)}" for s in STATUSES) + f" · all {len(points)}",
        "",
        "| ID | Section | Point | Owner | Status | Evidence |",
        "|---|---|---|---|---|---|",
    ]
    for p in points:
        text = " ".join(str(p.get("text", "")).split()).replace("|", "\\|")
        if len(text) > 160:
            text = text[:157] + "…"
        evidence = " ".join(str(p.get("evidence", "")).split()).replace("|", "\\|")
        if len(evidence) > 220:
            evidence = evidence[:217] + "…"
        lines.append(f"| {p['id']} | {p.get('section', '')} | {text} | {p.get('owner', '')} | "
                     f"{p.get('status', 'open')} | {evidence} |")
    TRACKER.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"rendered {TRACKER.relative_to(ROOT)}: " + ", ".join(f"{s} {counts.get(s, 0)}" for s in STATUSES))
    return 0


def summary() -> int:
    points = _load_points()
    by_owner: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    for p in points:
        by_owner[p.get("owner", "?")][p.get("status", "open")] += 1
    for owner in sorted(by_owner):
        c = by_owner[owner]
        print(f"{owner:<14} " + "  ".join(f"{s} {c.get(s, 0)}" for s in STATUSES))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--fold", action="store_true", help="fold docs/build_reports into plan_points.json")
    ap.add_argument("--render", action="store_true", help="render docs/PLAN_TRACKER.md")
    ap.add_argument("--summary", action="store_true", help="print status counts per owner")
    args = ap.parse_args()
    if not (args.fold or args.render or args.summary):
        args.fold = args.render = True
    rc = 0
    if args.fold:
        rc |= fold()
    if args.render:
        rc |= render()
    if args.summary:
        rc |= summary()
    return rc


if __name__ == "__main__":
    sys.exit(main())
