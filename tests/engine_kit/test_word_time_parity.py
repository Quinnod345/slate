"""The kit's TypeScript clock and slate.timing.words answer every word lookup the same way.

engine/tests/kit/fixtures/word-times.json holds a small neutral film's reads (with the `tokens` Python's resolver writes
into timing/vo_words.json), the language's match rules the engine inlines as '@film/data' `lang`, the spoken forms the
bridge inlines as `spoken`, and Python's own answer to each lookup (`word_time`: film seconds, exact or estimated).
engine/tests/kit/spoken.test.ts asks the kit the same questions and must get the same answers. This test keeps the
fixture true to Python: when the timing module changes, regenerate it with

    .venv/bin/python tests/engine_kit/test_word_time_parity.py --write
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
FIXTURE = REPO / "engine" / "tests" / "kit" / "fixtures" / "word-times.json"

FPS = 25
SHOTS = [("X1", 0, 50), ("X2", 50, 100), ("X3", 100, 150)]
CUES = {"X1": 0.2, "X2": 0.1, "X3": 0.0}
READS = {
    # "&" is the second "and": only the alignment knows that
    "X1": ("Sam and Jo run Salt & Stone.",
           [("Sam", 0.0, 0.3), ("and", 0.3, 0.45), ("Jo", 0.45, 0.7), ("run", 0.7, 0.95), ("Salt", 0.95, 1.3),
            ("and", 1.3, 1.45), ("Stone.", 1.45, 1.9)]),
    # Whisper wrote "12" for "Twelve" and split "664" into "six" "sixty-four"
    "X2": ("Twelve people came, 664 left.",
           [("12", 0.0, 0.3), ("people", 0.3, 0.7), ("came,", 0.7, 1.0), ("six", 1.1, 1.3), ("sixty-four", 1.3, 1.8),
            ("left.", 1.8, 2.1)]),
    # the read stops before "word": in the line, not heard
    "X3": ("Nobody heard this word.", [("Nobody", 0.0, 0.4), ("heard", 0.4, 0.7), ("this", 0.7, 0.9)]),
}
LOOKUPS = [
    ("X1", "&", 1, "start"), ("X1", "&", 1, "end"), ("X1", "and", 1, "start"), ("X1", "and", 2, "start"),
    ("X1", "Stone", 1, "end"), ("X1", "Jo", 2, "start"), ("X2", "Twelve", 1, "start"), ("X2", "12", 1, "start"),
    ("X2", "664", 1, "start"), ("X2", "664", 1, "end"), ("X2", "sixty-four", 1, "start"), ("X2", "left", 1, "end"),
    ("X3", "word", 1, "start"), ("X3", "absent", 1, "start"), ("X3", "this", 1, "end"),
]


def build() -> dict:
    """The fixture, computed now by slate.timing (and the engine bridge's spoken forms and language rules)."""
    from slate.engine import bridge
    from slate.timing import words as tw

    with tempfile.TemporaryDirectory(prefix="slate-word-times-") as tmp:
        film = Path(tmp) / "word-times"
        (film / "timing").mkdir(parents=True)
        film_json = {"id": "word-times", "language": "en", "fps_num": FPS, "fps_den": 1, "width": 320, "height": 180}
        (film / "film.json").write_text(json.dumps(film_json))
        shots = {"fps_num": FPS, "fps_den": 1, "width": 320, "height": 180, "total_frames": SHOTS[-1][2],
                 "shots": [{"id": sid, "act": 1, "frame_in": a, "frame_out": b, "frames": b - a,
                            "vo": READS[sid][0], "on_screen": ""} for sid, a, b in SHOTS]}
        cues = {"cues": [{"shot": sid, "at": at} for sid, at in CUES.items()]}
        vo_words = {"shots": {}}
        for sid, (line, heard) in READS.items():
            words = [{"w": w, "start": s, "end": e} for w, s, e in heard]
            vo_words["shots"][sid] = {"line": line, "words": words,
                                      "tokens": tw.resolve_tokens(line, words, (0.0, words[-1]["end"]))}
        for name, doc in (("shots", shots), ("vo_cues", cues), ("vo_words", vo_words)):
            (film / "timing" / f"{name}.json").write_text(json.dumps(doc))
        answers = []
        for sid, word, occ, which in LOOKUPS:
            t, exact = tw.word_time(film, sid, word, occ, which)
            answers.append({"shot": sid, "word": word, "occ": occ, "which": which, "t": round(t, 9), "exact": exact})
        return {
            "about": "Generated by tests/engine_kit/test_word_time_parity.py from slate.timing.words: a neutral "
                     "film's reads and Python's answer to each word lookup. The kit's clock must give the same "
                     "answers (engine/tests/kit/spoken.test.ts). Do not edit by hand.",
            "film": film_json, "shots": shots, "vo_cues": cues, "vo_words": vo_words,
            "spoken": bridge.spoken_map(film), "lang": bridge.lang_rules(film), "lookups": answers,
        }


def _text(doc: dict) -> str:
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def test_the_kit_fixture_matches_python_today():
    pytest.importorskip("slate.timing.words")
    assert FIXTURE.is_file(), f"{FIXTURE} is missing: run {Path(__file__).relative_to(REPO)} --write"
    assert FIXTURE.read_text(encoding="utf-8") == _text(build()), (
        f"{FIXTURE.relative_to(REPO)} is out of date with slate.timing: run "
        f".venv/bin/python {Path(__file__).relative_to(REPO)} --write")


def test_python_answers_the_hard_cases_the_way_the_fixture_says():
    """The cases the kit must get right, read as sentences: tokens first, then heard words, then honest estimates."""
    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    by = {(a["shot"], a["word"], a["occ"], a["which"]): a for a in doc["lookups"]}
    assert by[("X1", "&", 1, "start")] == {**by[("X1", "&", 1, "start")], "t": 1.5, "exact": True}  # 0.2 + 1.3
    assert by[("X1", "and", 1, "start")]["t"] == pytest.approx(0.5)  # the first "and" is the script's "and"
    assert by[("X2", "12", 1, "start")]["exact"] is True  # heard as written
    assert by[("X2", "664", 1, "end")]["t"] == pytest.approx(2.0 + 0.1 + 1.8)
    assert by[("X3", "word", 1, "start")]["exact"] is False  # in the line, not heard: estimated, never exact
    assert by[("X3", "absent", 1, "start")]["exact"] is False


if __name__ == "__main__":
    if "--write" in sys.argv:
        FIXTURE.write_text(_text(build()), encoding="utf-8")
        print(f"wrote {FIXTURE}")
    else:
        print("ok" if FIXTURE.read_text(encoding="utf-8") == _text(build()) else "stale: run with --write")
